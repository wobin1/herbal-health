/** Human-readable event start in the event's own IANA timezone, e.g. for emails and tickets. */
export function formatEventStart(startAt: Date, timezone: string): string {
  return new Intl.DateTimeFormat('en-US', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
    timeZone: timezone,
    timeZoneName: 'short',
  }).format(startAt);
}
